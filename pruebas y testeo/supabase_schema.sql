-- 1. TABLA DE CONTRATOS FISCALIZADOS
CREATE TABLE IF NOT EXISTS public.contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    sector TEXT NOT NULL,
    entity TEXT NOT NULL,
    contractor TEXT NOT NULL,
    amount TEXT NOT NULL,
    progress_physical INTEGER DEFAULT 0,
    progress_financial INTEGER DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'En Ejecución',
    status_type TEXT NOT NULL DEFAULT 'info',
    last_inspection TEXT,
    summary TEXT,
    file_path TEXT,
    external_link TEXT,
    source_report_code TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABLA DE DENUNCIAS Y REPORTES CIUDADANOS
CREATE TABLE IF NOT EXISTS public.reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL,
    subject TEXT NOT NULL,
    location TEXT NOT NULL,
    description TEXT NOT NULL,
    is_anonymous INTEGER DEFAULT 0,
    citizen_name TEXT,
    citizen_email TEXT,
    citizen_phone TEXT,
    evidence_file TEXT,
    status TEXT NOT NULL DEFAULT 'Recibido',
    admin_notes TEXT,
    is_approved INTEGER DEFAULT 0,
    approved_contract_id BIGINT REFERENCES public.contracts(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA DE CONFIGURACIONES DEL SISTEMA
CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- =============================================================================
-- CONFIGURACIÓN DE POLÍTICAS DE ACCESO (ROW LEVEL SECURITY - RLS)
-- =============================================================================
ALTER TABLE public.contracts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;

-- Políticas permisivas para la API pública y privada
DROP POLICY IF EXISTS "Acceso publico lectura contratos" ON public.contracts;
CREATE POLICY "Acceso publico lectura contratos" ON public.contracts FOR SELECT USING (true);

DROP POLICY IF EXISTS "Acceso total contratos" ON public.contracts;
CREATE POLICY "Acceso total contratos" ON public.contracts FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso publico radicar denuncias" ON public.reports;
CREATE POLICY "Acceso publico radicar denuncias" ON public.reports FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total denuncias" ON public.reports;
CREATE POLICY "Acceso total denuncias" ON public.reports FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total configuracion" ON public.settings;
CREATE POLICY "Acceso total configuracion" ON public.settings FOR ALL USING (true) WITH CHECK (true);

